// gen-manifest.ts — generates the per-view, per-entity drift manifest (fixtures/drift/entity-manifest
// .json) from the COMMITTED recorded fixtures, after anonymisation: plan 05 §3.1 step 4 (observed key
// sets, enum values, array-length ranges per view and entity; never hand-edited), plan 01 §7 (the
// in-call detector's manifest), research 03 §F.3 step 4. Offline; it refuses unless every fixture
// still hashes to the recording manifest (provenance) and the repo scanner passes the output.
//
// Usage:  scripts/dev/with-node.sh npx tsx scripts/gen-manifest.ts [--check]
//                                     [--fixtures <dir, default fixtures/>] [--out <file>]
//   --check writes nothing: exit 1 when the committed manifest is not what the fixtures generate.
// Exit: 0 written / current · 1 stale, refused or error · 2 usage.
